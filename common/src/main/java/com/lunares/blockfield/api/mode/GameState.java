package com.lunares.blockfield.api.mode;

public enum GameState {
    /** Покой. Матч не запущен. Игроки находятся в режиме песочницы или лобби ожидания. */
    IDLE,
    /**
     * Подготовка. Запущен таймер отсчета до начала матча. Игроки заблокированы или выбирают классы.
     */
    PREPARING,
    /**
     * Бой. Активная фаза геймплея. Начисляются очки, работают триггеры захватов и лимиты смертей.
     */
    GAME,
    /** Конец матча. Остановка логов, фиксация победителя, демонстрация финальной таблицы счета. */
    MATCH_END,
    /** Комната между матчами: игроки в хабе голосуют за следующую карту. */
    VOTING
}
